// Extracts the Solar icons the site uses from @iconify-json/solar into src/ui/icons.js.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const set = JSON.parse(readFileSync(new URL('../node_modules/@iconify-json/solar/icons.json', import.meta.url)));
const map = {
  arrowRight: 'arrow-right-linear', arrowLeft: 'arrow-left-linear', arrowDown: 'arrow-down-linear', arrowUp: 'arrow-up-linear',
  arrowUpRight: 'arrow-right-up-linear', bag: 'bag-4-linear', menu: 'hamburger-menu-linear', close: 'close-linear',
  plus: 'add-circle-linear', minus: 'minus-circle-linear', trash: 'trash-bin-minimalistic-linear', check: 'check-circle-linear',
  lock: 'lock-keyhole-minimalistic-linear', clock: 'clock-circle-linear', info: 'info-circle-linear', letter: 'letter-linear',
  chevronRight: 'alt-arrow-right-linear', chevronDown: 'alt-arrow-down-linear', box: 'box-linear', shield: 'shield-check-linear',
  delivery: 'delivery-linear', undo: 'undo-left-round-linear', danger: 'danger-circle-linear', refresh: 'refresh-linear',
};

const out = {};
for (const [key, name] of Object.entries(map)) {
  const icon = set.icons[name];
  if (!icon) throw new Error('missing ' + name);
  out[key] = `<svg xmlns="http://www.w3.org/2000/svg" width="1em" height="1em" viewBox="0 0 24 24" aria-hidden="true" focusable="false">${icon.body}</svg>`;
}

mkdirSync(new URL('../src/ui/', import.meta.url), { recursive: true });
const src = `// Solar icon set by 480 Design (CC BY 4.0), via Iconify. Generated by scripts/extract-icons.mjs, do not edit by hand.
export const ICONS = ${JSON.stringify(out, null, 2)};

export const icon = (name) => ICONS[name] ?? '';
`;
writeFileSync(new URL('../src/ui/icons.js', import.meta.url), src);
console.log(Object.keys(out).length, 'icons written');
